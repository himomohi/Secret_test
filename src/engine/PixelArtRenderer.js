// 픽셀 아트 렌더링 유틸리티
class PixelArtRenderer {
    constructor(ctx) {
        this.ctx = ctx;
    }

    // 픽셀 아트 스프라이트 그리기
    drawSprite(x, y, pixelData, scale = 1) {
        const pixelSize = 2 * scale;

        for (let row = 0; row < pixelData.length; row++) {
            for (let col = 0; col < pixelData[row].length; col++) {
                const color = pixelData[row][col];
                if (color && color !== 'transparent' && color !== 0) {
                    this.ctx.fillStyle = color;
                    this.ctx.fillRect(
                        Math.floor(x + col * pixelSize),
                        Math.floor(y + row * pixelSize),
                        pixelSize,
                        pixelSize
                    );
                }
            }
        }
    }

    // 외곽선 그리기
    drawOutline(x, y, width, height, color = '#000000', thickness = 1) {
        this.ctx.fillStyle = color;
        // 위
        this.ctx.fillRect(x, y, width, thickness);
        // 아래
        this.ctx.fillRect(x, y + height - thickness, width, thickness);
        // 왼쪽
        this.ctx.fillRect(x, y, thickness, height);
        // 오른쪽
        this.ctx.fillRect(x + width - thickness, y, thickness, height);
    }

    // 그림자 효과
    drawShadow(x, y, width, height) {
        this.ctx.fillStyle = 'rgba(0, 0, 0, 0.3)';
        this.ctx.beginPath();
        this.ctx.ellipse(
            Math.floor(x + width / 2),
            Math.floor(y + height + 2),
            width / 2,
            3,
            0, 0, Math.PI * 2
        );
        this.ctx.fill();
    }

    // 체력바 (더 세련된)
    drawHealthBar(x, y, width, currentHealth, maxHealth) {
        const barHeight = 4;
        const barY = y - 8;

        // 배경
        this.ctx.fillStyle = '#2a2a2a';
        this.ctx.fillRect(x, barY, width, barHeight);

        // 테두리
        this.ctx.strokeStyle = '#000000';
        this.ctx.lineWidth = 1;
        this.ctx.strokeRect(x, barY, width, barHeight);

        // 체력
        const healthPercent = currentHealth / maxHealth;
        let healthColor;
        if (healthPercent > 0.6) healthColor = '#44ff44';
        else if (healthPercent > 0.3) healthColor = '#ffaa00';
        else healthColor = '#ff4444';

        const healthWidth = Math.max(0, width * healthPercent - 2);
        if (healthWidth > 0) {
            this.ctx.fillStyle = healthColor;
            this.ctx.fillRect(x + 1, barY + 1, healthWidth, barHeight - 2);

            // 하이라이트
            this.ctx.fillStyle = 'rgba(255, 255, 255, 0.3)';
            this.ctx.fillRect(x + 1, barY + 1, healthWidth, 1);
        }
    }
}

